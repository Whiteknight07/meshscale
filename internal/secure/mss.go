package secure

import (
	"encoding/binary"

	"golang.zx2c4.com/wireguard/tun"
)

// mssTUN adjusts SYN options in the private netstack in both directions. The
// stack has no host firewall; this preserves IPv6's minimum interface MTU while
// bounding TCP packets to the measured carrier. Data packets take a no-op path.
type mssTUN struct {
	tun.Device
	mss uint16
}

func (t *mssTUN) Read(bufs [][]byte, sizes []int, offset int) (int, error) {
	n, err := t.Device.Read(bufs, sizes, offset)
	for i := 0; i < n; i++ {
		clampTCPMSS(bufs[i][offset:offset+sizes[i]], t.mss)
	}
	return n, err
}
func (t *mssTUN) Write(bufs [][]byte, offset int) (int, error) {
	for _, buf := range bufs {
		clampTCPMSS(buf[offset:], t.mss)
	}
	return t.Device.Write(bufs, offset)
}

// clampTCPMSS updates the TCP checksum incrementally (RFC 1624). Only direct
// IPv6/TCP SYNs generated by our stack are eligible; other packets are untouched.
func clampTCPMSS(packet []byte, maxMSS uint16) {
	if len(packet) < 60 || packet[0]>>4 != 6 || packet[6] != 6 {
		return
	}
	tcp := packet[40:]
	if tcp[13]&2 == 0 {
		return
	}
	end := int(tcp[12]>>4) * 4
	if end < 20 || end > len(tcp) {
		return
	}
	for i := 20; i < end; {
		kind := tcp[i]
		if kind == 0 {
			return
		}
		if kind == 1 {
			i++
			continue
		}
		if i+1 >= end {
			return
		}
		size := int(tcp[i+1])
		if size < 2 || i+size > end {
			return
		}
		if kind == 2 && size == 4 {
			old := binary.BigEndian.Uint16(tcp[i+2 : i+4])
			if old <= maxMSS {
				return
			}
			checksum := binary.BigEndian.Uint16(tcp[16:18])
			oldWord, newWord := old, maxMSS
			if (i+2)%2 != 0 {
				oldWord = old<<8 | old>>8
				newWord = maxMSS<<8 | maxMSS>>8
			}
			sum := uint32(^checksum) + uint32(^oldWord) + uint32(newWord)
			for sum>>16 != 0 {
				sum = (sum & 0xffff) + (sum >> 16)
			}
			binary.BigEndian.PutUint16(tcp[16:18], ^uint16(sum))
			binary.BigEndian.PutUint16(tcp[i+2:i+4], maxMSS)
			return
		}
		i += size
	}
}
